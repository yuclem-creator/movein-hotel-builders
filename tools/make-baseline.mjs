// make-baseline.mjs — the regression lock. Run ONCE, against the engine as shipped,
// and commit the result: from then on every gate compares the current engine to this
// file and fails on the first difference.
//
// Why a file rather than "the numbers we remember": the three features that follow
// (journeys, per-building customisation, sellable land) all touch the same scoring and
// walk code. A lock that lives in prose gets re-derived by whoever is refactoring, and
// a lock that lives in a head gets quietly updated to match the new behaviour. This one
// is machine-checked, so "no change" means byte-identical, not "looks about right".
//
// Deliberately NOT regenerated by any gate. If a change to the baseline is genuinely
// intended (a balance fix), Clement approves it and this file is re-run by hand.
import { writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  createSession, autoBuild, runRound, advanceRound, evaluateLayout, PRESETS,
} from '../js/sim/engine.js';
import { ROUNDS } from '../js/sim/catalogue.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SEED = 'hb-baseline';

/** Every round of a preset, exactly as sim-check drives it. */
export function playOut(preset) {
  const s = createSession({ seed: SEED, style: 'tower', palette: 'gold' });
  autoBuild(s, preset);
  const rounds = [];
  while (s.round <= ROUNDS.length) {
    const r = runRound(s);
    rounds.push({
      round: r.round,
      metrics: r.metrics,
      composite: r.composite,
      events: r.events.map((e) => e.id),
      // The note text is part of the contract: a ledger entry whose wording changed is
      // still a change a player would see on the result card.
      ledger: r.ledger.map((c) => ({ metric: c.metric, code: c.code, delta: c.delta, note: c.note })),
    });
    if (!advanceRound(s).ok) break;
  }
  return rounds;
}

/** The layout-only scorecard at round 4, plus the preset's exact footprint. */
export function layoutAtFour(preset) {
  const s = createSession({ seed: SEED, style: 'tower', palette: 'gold' });
  autoBuild(s, preset);
  while (s.round < 4) advanceRound(s);
  const l = evaluateLayout(s, 4);
  return {
    metrics: l.metrics,
    causes: l.causes.map((c) => ({ metric: c.metric, code: c.code, delta: c.delta, note: c.note })),
    journeys: l.journeys.map((j) => ({
      id: j.id, label: j.label, friction: j.friction, gaps: j.gaps,
      quality: j.quality, optionalHits: j.optionalHits,
      stops: j.stops.map((x) => ({ tag: x.tag, owner: x.owner ?? null, resolved: !!x.resolved, uid: x.uid ?? null })),
    })),
    // Placement geometry, not just the score: a preset that lands in the same cells
    // keeps its walks, and a walk that silently moved is exactly what the journey
    // work is most likely to disturb.
    placements: s.placements.map((p) => ({ fnId: p.fnId, col: p.col, row: p.row, w: p.w, h: p.h, rot: p.rot, round: p.round })),
  };
}

/** The whole baseline in memory. Used by both the generator and the gate. */
export function snapshot() {
  const out = {
    note: 'Regression baseline for MOVEin Hotel Builders. Generated once from the shipped engine; do not regenerate without approval.',
    seed: SEED,
    presets: {},
  };
  for (const id of Object.keys(PRESETS)) {
    out.presets[id] = { rounds: playOut(id), layout: layoutAtFour(id) };
  }
  return out;
}

// Writing is a side effect of running this file, never of importing it: sim-check
// imports snapshot() to compare against the committed baseline, and a gate that
// silently rewrote the baseline would always pass.
const runDirectly = process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url;
if (runDirectly) {
  const out = snapshot();
  const path = join(ROOT, 'tools/baseline.json');
  await writeFile(path, `${JSON.stringify(out, null, 2)}\n`, 'utf8');
  const rounds = Object.values(out.presets).reduce((n, p) => n + p.rounds.length, 0);
  console.log(`baseline written: ${path}`);
  console.log(`  presets ${Object.keys(out.presets).length}, rounds compared ${rounds}`);
}
